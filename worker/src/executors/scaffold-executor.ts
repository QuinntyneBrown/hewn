import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { CommitFile, LeasedRun } from '../api.ts';
import type { StackTemplate } from '../scaffold/stack-template.ts';
import { checkOut } from './checkout.ts';
import type { RunContext, StageExecutor, StageStep } from './stage-executor.ts';

const BRANCH = 'hewn/scaffold';
const TITLE = 'Scaffold the solution';
const OPEN_STEP = 2;
const MERGE_STEP = 4;
const PASSING = new Set(['success', 'neutral', 'skipped']);

export interface ScaffoldOptions {
  /** How often to read the pull request's checks. */
  pollMs?: number;
  /** How long CI may take before the run fails. */
  timeoutMs?: number;
}

/**
 * Stage 6 (L2-015, L2-036 AC2): generate the scaffold for the stack stage 4 chose, commit it to `hewn/scaffold`,
 * open a pull request, wait for its CI checks, then squash-merge it and require those checks on the default
 * branch. Failed CI fails the run (L2-015 AC4); every GitHub write goes through the API with the run's keys.
 */
export class ScaffoldStageExecutor implements StageExecutor {
  private readonly templates: readonly StackTemplate[];
  private readonly pollMs: number;
  private readonly timeoutMs: number;

  constructor(templates: readonly StackTemplate[], options: ScaffoldOptions = {}) {
    this.templates = templates;
    this.pollMs = options.pollMs ?? 30_000;
    this.timeoutMs = options.timeoutMs ?? 60 * 60_000;
  }

  plan(leased: LeasedRun, context: RunContext): StageStep[] {
    const directory = join(context.workspace, 'repository');
    let generated: { template: StackTemplate; files: CommitFile[] } | null = null;
    const generate = async () => (generated ??= await this.generate(leased, context, directory));
    const open = async () =>
      context.openPullRequest(OPEN_STEP, {
        head: BRANCH,
        title: TITLE,
        body: `Generated by Hewn from the stack decision in docs/adr/0001-stack.md.\n\nCI must pass before this merges; afterwards the default branch requires the same checks.`,
      });

    return [
      { name: 'Generate scaffold', execute: async () => void (await generate()) },
      {
        name: 'Open pull request',
        execute: async () => {
          const { files } = await generate();
          await context.commit(OPEN_STEP, TITLE, files, BRANCH);
          const pull = await open();
          await context.log('info', `Opened pull request #${pull.number}: ${pull.url}`);
        },
      },
      {
        name: 'Wait for checks',
        execute: async (signal) => {
          const { template } = await generate();
          await this.waitForChecks((await open()).number, template, context, signal);
        },
      },
      {
        name: 'Merge and protect',
        execute: async () => {
          const { template } = await generate();
          const pull = await open();
          await context.mergePullRequest(MERGE_STEP, pull.number);
          await context.protectDefaultBranch(MERGE_STEP, [...template.checks]);
          await context.log(
            'info',
            `Merged #${pull.number}; the default branch now requires ${template.checks.join(', ')}`,
          );
        },
      },
    ];
  }

  private async generate(leased: LeasedRun, context: RunContext, directory: string) {
    if (!existsSync(directory)) await checkOut(context, directory);
    const decision = stackDecision(directory);
    const template = this.templates.find((t) => t.matches(decision));
    if (!template) throw new Error(`No scaffold template for the chosen stack: ${firstLine(decision)}`);
    const files = template
      .generate(leased.project.name)
      .map((f) => ({ path: f.path, content: Buffer.from(f.content) }));
    await context.log('info', `Generated ${files.length} files from the ${template.id} template`);
    return { template, files };
  }

  private async waitForChecks(number: number, template: StackTemplate, context: RunContext, signal: AbortSignal) {
    const deadline = Date.now() + this.timeoutMs;
    while (true) {
      const checks = await context.pullRequestChecks(number);
      const finished = template.checks.every((name) => checks.some((c) => c.name === name && c.status === 'completed'));
      if (finished) {
        const failed = checks.filter((c) => c.status === 'completed' && !PASSING.has(c.conclusion ?? ''));
        if (failed.length > 0) {
          throw new Error(`CI failed on the scaffold pull request #${number}: ${failed.map((c) => c.name).join(', ')}`);
        }
        await context.log('info', `CI passed on pull request #${number}: ${template.checks.join(', ')}`);
        return;
      }
      if (signal.aborted) throw new Error('Stopped while waiting for CI');
      if (Date.now() + this.pollMs > deadline) {
        throw new Error(
          `CI did not finish on the scaffold pull request #${number} in ${Math.round(this.timeoutMs / 60_000)} minutes`,
        );
      }
      await new Promise((resolve) => setTimeout(resolve, this.pollMs));
    }
  }
}

/** The Decision section of stage 4's stack ADR. */
export function stackDecision(directory: string): string {
  const path = join(directory, 'docs/adr/0001-stack.md');
  if (!existsSync(path)) throw new Error('docs/adr/0001-stack.md does not exist; stage 4 chooses the stack');
  const text = readFileSync(path, 'utf8');
  return (text.split(/^## Decision\s*$/m)[1]?.split(/^## /m)[0] ?? '').trim();
}

function firstLine(text: string): string {
  return text.split('\n')[0]?.trim() || '(empty decision)';
}
