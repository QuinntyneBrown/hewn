"""Write tokens/tokens.css and tokens/contrast-pairs.json from tokens.py."""
import json
from pathlib import Path

from tokens import (COLOR, DERIVED, FONT, INTERACTION, LAYOUT, MOTION, PAIRS, PALETTE, SHADOW_DARK, SHADOW_LIGHT,
                    SHAPE, SPACE, TYPE_ROLES, Z)

HEADER = """/* ==========================================================================
   Hewn design tokens: the single source of truth for colour, type, space,
   layout, shape, elevation, motion, z-order and interaction sizes.

   GENERATED by docs/design-system/_build/build.py from _build/tokens.py.
   Edit the Python data, not this file.

   Extracted from docs/mocks (the Mission Control prototype in Magic
   Patterns). Dark carries the prototype's palette; light is derived from the
   same roles and verified for WCAG 2.2 AA (tokens/contrast-pairs.json).

   Tiers
     1. Primitives  --palette-*, --font-*           raw values; only semantic tokens read them
     2. Semantic    --color-*, --text-*, --space-*, --layout-*, --radius-*,
                    --shadow-*, --duration-*, --ease-*, --z-*, --target-*,
                    --control-height-*, --size-icon-*   what components read; themes override colour + shadow only
     3. Component   --btn-*, --field-*, --dialog-* ...  declared in assets/components.css

   Themes
     light   :root (default) and [data-theme="light"] (restates light inside a dark page)
     dark    [data-theme="dark"], and the OS preference unless the page forces light
   ========================================================================== */
"""


def block(selector, lines, indent="  "):
    body = "\n".join(f"{indent}  {l}" if l and not l.startswith("/*") else f"{indent}  {l}" for l in lines)
    return f"{indent}{selector} {{\n{body}\n{indent}}}\n"


def theme_lines(which):
    i = 1 if which == "light" else 2
    lines = ["/* colour */"]
    lines += [f"{t[0]}: {t[i]};" for t in COLOR]
    lines += [f"{name}: {value};" for name, value, _ in DERIVED]
    lines.append("/* elevation */")
    lines += [f"{n}: {v};" for n, v, *_ in (SHADOW_LIGHT if which == "light" else SHADOW_DARK)]
    lines.append(f"color-scheme: {which};")
    return lines


def tokens_css():
    root = ["/* ---------- Primitives: colour ---------- */"]
    for ramp, steps in PALETTE.items():
        for step, hexv, note in steps:
            root.append(f"--palette-{ramp}-{step}: {hexv};  /* {note} */")
    root.append("/* ---------- Primitives: type ---------- */")
    root += [f"{n}: {v};" for n, v in FONT]
    root.append("/* ---------- Semantic: typography roles (font shorthands) ---------- */")
    for n, w, s, lh, fam, _ in TYPE_ROLES:
        root.append(f"{n}: var(--font-weight-{w}) var(--font-size-{s}) / var(--line-height-{lh}) var(--font-family-{fam});")
    root.append("/* ---------- Semantic: spacing (4px base; half steps for dense parts) ---------- */")
    root += [f"--space-{k}: {v};" for k, v in SPACE]
    root.append("/* ---------- Semantic: layout ---------- */")
    root += [f"{n}: {v};" for n, v, _ in LAYOUT]
    root.append("/* ---------- Semantic: shape ---------- */")
    root += [f"{n}: {v};" for n, v, _ in SHAPE]
    root.append("/* ---------- Semantic: motion ---------- */")
    root += [f"{n}: {v};" for n, v, _ in MOTION]
    root.append("/* ---------- Semantic: z-order ---------- */")
    root += [f"{n}: {v};" for n, v, _ in Z]
    root.append("/* ---------- Semantic: interaction and icon sizes ---------- */")
    root += [f"{n}: {v};" for n, v, _ in INTERACTION]
    root.append("/* ---------- Light theme (default) ---------- */")
    root += theme_lines("light")

    out = [HEADER, block(":root", root, indent="")]
    out.append("\n/* Grid steps up at md and lg. Custom properties cannot be used in @media, so the breakpoints are repeated. */\n")
    out.append("@media (min-width: 48rem) {\n" + block(":root", ["--layout-columns: 8;", "--layout-gutter: var(--space-6);"]) + "}\n")
    out.append("@media (min-width: 62rem) {\n" + block(":root", ["--layout-columns: 12;", "--layout-gutter: var(--space-8);", "--layout-margin: var(--space-8);", "--control-height-sm: 2rem;", "--control-height-md: 2.5rem;"]) + "}\n")
    out.append("\n/* ---------- Light restated, so a [data-theme=\"light\"] island inside a dark page is light ---------- */\n")
    out.append(block('[data-theme="light"]', theme_lines("light"), indent=""))
    out.append("\n/* ---------- Dark theme: the prototype's own palette. Keep both dark blocks identical. ---------- */\n")
    out.append(block('[data-theme="dark"]', theme_lines("dark"), indent=""))
    out.append("\n@media (prefers-color-scheme: dark) {\n" + block(':root:not([data-theme="light"])', theme_lines("dark")) + "}\n")
    out.append("""
/* ---------- Reduced motion: transitions become instant; loops stop (0s, never a flashing 0.01ms loop) ---------- */
@media (prefers-reduced-motion: reduce) {
  :root {
    --duration-fast: 0.01ms;
    --duration-base: 0.01ms;
    --duration-slow: 0.01ms;
    --duration-deliberate: 0.01ms;
    --duration-pulse: 0s;
    --duration-spin: 0s;
  }
}

/* ---------- More contrast: hairlines and faint text step up ---------- */
@media (prefers-contrast: more) {
  :root, [data-theme] {
    --color-border-default: var(--color-border-strong);
    --color-fg-subtle: var(--color-fg-muted);
  }
}

/* ---------- Forced colours: hand rings and edges to the system ---------- */
@media (forced-colors: active) {
  :root, [data-theme] {
    --color-focus-ring: Highlight;
    --color-border-default: CanvasText;
    --color-border-strong: CanvasText;
  }
}
""")
    return "".join(out)


def write(root: Path):
    (root / "tokens").mkdir(parents=True, exist_ok=True)
    (root / "tokens" / "tokens.css").write_text(tokens_css(), encoding="utf-8")
    data = {
        "$comment": "Foreground/background token pairs checked by check_contrast.py in both themes. 4.5:1 = WCAG 2.2 AA text (1.4.3); 3:1 = UI component edges, meaningful graphics and focus (1.4.11, 2.4.11). Generated from _build/tokens.py.",
        "pairs": [p for p in PAIRS],
    }
    (root / "tokens" / "contrast-pairs.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    write(Path(__file__).resolve().parent.parent)
