// Acceptance Test
// Traces to: L2-015, L2-036
// Description: Stage 6 commits the scaffold to its own branch, opens a pull request, reads its checks, merges it and requires the checks on the default branch

using System.Net;
using System.Net.Http.Json;
using System.Text;
using System.Text.Json;
using Hewn.Api.Tests.Support;
using Hewn.Domain;

namespace Hewn.Api.Tests.Pipeline;

public sealed class ScaffoldStageTests : IAsyncLifetime
{
    private const string Branch = "hewn/scaffold";
    private const string Ci = "name: CI\non: [push, pull_request]\njobs:\n  backend:\n    runs-on: ubuntu-latest\n    steps: []\n  frontend:\n    runs-on: ubuntu-latest\n    steps: []\n  e2e:\n    runs-on: ubuntu-latest\n    steps: []\n";

    private readonly HewnApiFactory _factory = new();

    public Task InitializeAsync() => Task.CompletedTask;

    public async Task DisposeAsync() => await _factory.DisposeAsync();

    private async Task<(WorkerClient Worker, LeasedRun Run)> LeaseStageAsync(int stage)
    {
        var owner = await _factory.SignInAsync("quinntynebrown", Role.Owner);
        (await owner.PostAsync("/api/projects", new
        {
            name = "Ledgerline",
            idea = "A web app for small accounting teams to reconcile statements.",
            stackPreference = (string?)null,
            repositoryUrl = (string?)null,
            budgetUsd = 300m,
        })).EnsureSuccessStatusCode();
        var worker = await _factory.RegisterWorkerAsync();
        while (true)
        {
            var run = await worker.LeaseAsync() ?? throw new InvalidOperationException($"Stage {stage} was never offered.");
            if (run.Stage == stage)
            {
                return (worker, run);
            }

            (await worker.SucceedAsync(run)).EnsureSuccessStatusCode();
        }
    }

    private static Task<HttpResponseMessage> MutateAsync(WorkerClient worker, LeasedRun run, string kind, string key, object fields)
    {
        var body = JsonSerializer.SerializeToElement(fields).EnumerateObject()
            .ToDictionary(p => p.Name, p => (object?)p.Value);
        body["workerId"] = worker.WorkerId;
        body["epoch"] = run.Epoch;
        body["kind"] = kind;
        body["idempotencyKey"] = $"{run.RunId}/{key}";
        return worker.Http.PostAsJsonAsync($"/api/worker/runs/{run.RunId}/github/mutations", body);
    }

    private static object Files(params (string Path, string Content)[] files) =>
        files.Select(f => new { path = f.Path, contentBase64 = Convert.ToBase64String(Encoding.UTF8.GetBytes(f.Content)) }).ToArray();

    private static async Task<int> OpenAsync(WorkerClient worker, LeasedRun run)
    {
        (await MutateAsync(worker, run, "commit", "2/commit", new
        {
            message = "Scaffold the solution",
            branch = Branch,
            files = Files((".github/workflows/ci.yml", Ci), ("README.md", "# Ledgerline\n"), ("backend/Ledgerline.slnx", "<Solution />")),
        })).EnsureSuccessStatusCode();
        var opened = await MutateAsync(worker, run, "open_pull_request", "2/pull-request", new { head = Branch, title = "Scaffold the solution", body = "Generated by Hewn." });
        opened.EnsureSuccessStatusCode();
        return (await HewnClient.ReadJsonAsync(opened)).GetProperty("number").GetInt32();
    }

    private static async Task<JsonElement> ChecksAsync(WorkerClient worker, LeasedRun run, int number)
    {
        var response = await worker.Http.GetAsync($"/api/worker/runs/{run.RunId}/pull-requests/{number}/checks?workerId={worker.WorkerId}&epoch={run.Epoch}");
        response.EnsureSuccessStatusCode();
        return (await HewnClient.ReadJsonAsync(response)).GetProperty("checks");
    }

    [Fact]
    public async Task The_scaffold_is_merged_through_a_pull_request_whose_checks_become_required()
    {
        var (worker, run) = await LeaseStageAsync(6);
        var repository = _factory.GitHub.Repository("hewn-builds", "ledgerline")!;

        var number = await OpenAsync(worker, run);
        Assert.NotEqual("# Ledgerline\n", repository.Read("README.md")); // not on the default branch until merged

        var checks = await ChecksAsync(worker, run, number);
        Assert.Equal(["backend", "frontend", "e2e"], checks.EnumerateArray().Select(c => c.GetProperty("name").GetString()));
        Assert.All(checks.EnumerateArray(), c => Assert.Equal("success", c.GetProperty("conclusion").GetString()));

        var merged = await MutateAsync(worker, run, "merge_pull_request", "4/merge", new { number });
        merged.EnsureSuccessStatusCode();
        (await MutateAsync(worker, run, "protect_branch", "4/protect", new { checks = new[] { "backend", "frontend", "e2e" } })).EnsureSuccessStatusCode();

        Assert.Equal("# Ledgerline\n", repository.Read("README.md"));
        Assert.True(repository.PullRequests.Single().Merged);
        Assert.Equal(["backend", "frontend", "e2e"], repository.RequiredChecks);
    }

    [Fact]
    public async Task Opening_the_pull_request_twice_with_one_key_returns_the_same_pull_request()
    {
        var (worker, run) = await LeaseStageAsync(6);
        var number = await OpenAsync(worker, run);

        var again = await MutateAsync(worker, run, "open_pull_request", "2/pull-request", new { head = Branch, title = "Scaffold the solution", body = "Generated by Hewn." });

        Assert.Equal(number, (await HewnClient.ReadJsonAsync(again)).GetProperty("number").GetInt32());
        Assert.Single(_factory.GitHub.Repository("hewn-builds", "ledgerline")!.PullRequests);
    }

    [Fact]
    public async Task A_failing_check_is_reported_with_its_conclusion()
    {
        var (worker, run) = await LeaseStageAsync(6);
        _factory.GitHub.FailCheck("hewn-builds", "ledgerline", "frontend");
        var number = await OpenAsync(worker, run);

        var checks = await ChecksAsync(worker, run, number);

        Assert.Equal("failure", checks.EnumerateArray().Single(c => c.GetProperty("name").GetString() == "frontend").GetProperty("conclusion").GetString());
    }

    [Theory]
    [InlineData(null, "README.md", "branch_not_allowed")]
    [InlineData("feature/x", "README.md", "branch_not_allowed")]
    [InlineData(Branch, "docs/brief.md", "path_not_allowed")]
    [InlineData(Branch, ".claude/skills/grilling/SKILL.md", "path_not_allowed")]
    public async Task The_scaffold_commits_only_to_its_branch_and_outside_the_stage_documents(string? branch, string path, string code)
    {
        var (worker, run) = await LeaseStageAsync(6);

        var response = await MutateAsync(worker, run, "commit", "2/commit", new { message = "Scaffold", branch, files = Files((path, "x")) });

        Assert.Equal(HttpStatusCode.BadRequest, response.StatusCode);
        Assert.Equal(code, (await HewnClient.ReadJsonAsync(response)).GetProperty("code").GetString());
    }

    [Fact]
    public async Task Other_stages_may_not_use_branches_or_pull_requests()
    {
        var (worker, run) = await LeaseStageAsync(5);

        var commit = await MutateAsync(worker, run, "commit", "1/commit", new { message = "x", branch = Branch, files = Files(("docs/specs/L1.md", "x")) });
        var open = await MutateAsync(worker, run, "open_pull_request", "1/pr", new { head = Branch, title = "x", body = "x" });
        var protect = await MutateAsync(worker, run, "protect_branch", "1/protect", new { checks = new[] { "backend" } });

        Assert.Equal("branch_not_allowed", (await HewnClient.ReadJsonAsync(commit)).GetProperty("code").GetString());
        Assert.Equal("mutation_not_allowed", (await HewnClient.ReadJsonAsync(open)).GetProperty("code").GetString());
        Assert.Equal("mutation_not_allowed", (await HewnClient.ReadJsonAsync(protect)).GetProperty("code").GetString());
    }
}
